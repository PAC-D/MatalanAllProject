export const registrationCountries = [...new Set(registrationPairs.map((pair) => pair.supplierCountry))]
  .sort((a, b) => a.localeCompare(b));

export function getSuppliersForCountry(country) {
  const normalizedCountry = country.trim().toLocaleLowerCase();
  return registrationPairs
    .filter((pair) => pair.supplierCountry.toLocaleLowerCase() === normalizedCountry)
    .map((pair) => pair.supplier)
    .filter((supplier, index, suppliers) => suppliers.indexOf(supplier) === index)
    .sort((a, b) => a.localeCompare(b));
}

export function getFactoriesForSupplier(supplier) {
  const normalizedSupplier = supplier.trim().toLocaleLowerCase();
  return registrationPairs
    .filter((pair) => pair.supplier.toLocaleLowerCase() === normalizedSupplier)
    .map((pair) => ({ name: pair.factory, country: pair.factoryCountry }));
}

function matchScore(value, query) {
  const normalized = value.toLocaleLowerCase();
  if (normalized === query) return 0;
  if (normalized.startsWith(query)) return 1;
  if (normalized.split(/\s+/).some((word) => word.startsWith(query))) return 2;
  if (normalized.includes(query)) return 3;
  return Number.POSITIVE_INFINITY;
}

export function getOrganizationSuggestions(value) {
  const query = value.trim().toLocaleLowerCase();
  if (!query) return [];

  return registrationPairs
    .map((pair) => {
      const supplierScore = matchScore(pair.supplier, query);
      const factoryScore = matchScore(pair.factory, query);
      if (!Number.isFinite(supplierScore) && !Number.isFinite(factoryScore)) return null;
      return {
        label: `${pair.supplier} / ${pair.factory}`,
        value: factoryScore < supplierScore ? pair.factory : pair.supplier,
        pair: `${pair.supplier} / ${pair.factory}`,
        score: Math.min(supplierScore, factoryScore),
      };
    })
    .filter(Boolean)
    .sort((a, b) => a.score - b.score || a.label.localeCompare(b.label))
    .slice(0, 12);
}
